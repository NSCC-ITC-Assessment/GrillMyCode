package org.grillmycode.companion.shared

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull

/*
 * Report reader
 *
 * Reads the questions out of the Markdown report the GrillMyCode action posts
 * as an issue. A port of extensions/vscode/src/shared/report.js, which says
 * more about the layout; both are tested against extensions/fixtures/.
 *
 * The issue text is untrusted: anyone who can write to the repository can edit
 * it. Nothing here evaluates it, and a report that does not fit the expected
 * shape yields fewer questions, or null, never an exception.
 */

/** One piece of code a question shows, with where it is in the repository. */
data class Snippet(
    val file: String,
    val startLine: Int,
    val endLine: Int,
    val language: String,
    val code: String,
)

/**
 * A question, as the report gives it. [answer] is there only when the
 * instructor set include_answers. An answer key's question always has an
 * answer, and adds [distractors] (parseAnswerKey in instructor/AnswerKey.kt).
 */
data class Question(
    val number: Int,
    val broader: Boolean,
    val snippets: List<Snippet>,
    val question: String,
    val answer: String? = null,
    val distractors: List<String> = emptyList(),
)

/** What [parseReport] reads from a questions issue. */
sealed interface ParsedReport

/**
 * A report in a layout this plugin reads.
 *
 * [baseSha] and [headSha] are the short SHAs the report prints. [headCommit] is
 * the full SHA behind [headSha], there when the issue carries its hidden data.
 * [branch] is null for the default branch, which the report does not name, and
 * [tag] is null unless a submission tag started the run. [set] is the question
 * set's folder name, from the hidden data, for a set's issue. [truncated] is
 * true when the report stops before its footer, so the last questions are
 * missing.
 */
data class Report(
    val baseSha: String,
    val headSha: String,
    val headCommit: String?,
    val branch: String?,
    val tag: String?,
    val set: String? = null,
    val files: List<String>,
    val questions: List<Question>,
    val truncated: Boolean,
) : ParsedReport

/** A report in a layout newer than this plugin reads. None of it is read. */
data object NeedsUpdate : ParsedReport

/** Zero-width space, which the action puts after `@` and `#` to stop GitHub linking them. */
private const val ZWSP = "​"

private val HEADING = Regex("""^## .*GrillMyCode\s*$""")
private val COMMITS = Regex("""^> \*\*Commits reviewed:\*\* `([0-9a-f]+)` → `([0-9a-f]+)`""")
private val BRANCH = Regex("""^> \*\*Branch:\*\* `(.+)`\s*$""")
private val TAG = Regex("""^> \*\*Submission tag:\*\* `([^`]+)`""")
private val FILES = Regex("""^> \*\*Code Files Assessed:\*\* (.*)$""")
private val RULE = Regex("""^---\s*$""")
private val QUESTION_LABEL = Regex("""^\*\*Question (\d+):\*\*\s*$""")
private val BROADER_HEADING = Regex("""^## Broader Questions\s*$""")
private val CAPTION = Regex("""^\*\*`(.+)`\*\*, lines? (\d+)(?:–(\d+))?\s*$""")
private val FENCE_OPEN = Regex("""^(`{3,})([^`\s]*)\s*$""")
private val ANSWER_LABEL = Regex("""^\*\*Answer:\*\*\s*$""")
private val FOOTER = Regex("""^_Generated by \*\*GrillMyCode\*\*""")
private val CUT_NOTICE = Regex("""^> \[!WARNING]\s*$""")
private val DATA_COMMENT = Regex("""^<!-- gmc:questions (.*) -->\s*$""")
private val FULL_SHA = Regex("""^[0-9a-f]{40,64}$""")

// A question set's folder name, as questionSetSlug in src/context.js writes it.
// It becomes part of the answer key's path, so nothing else is accepted.
private val SET_SLUG = Regex("^[a-z0-9_-]{1,$QUESTION_SET_MAX_CHARS}$")
private val CODE_SPAN = Regex("""`[^`]+`""")
private val LINE_BREAK = Regex("""\r?\n""")

/** The facts the hidden data comment gives for one question. */
private data class QuestionFacts(
    val number: Int,
    val broader: Boolean,
    val snippets: List<Triple<String, Int, Int>>,
)

/** What the hidden data comment holds: a layout this plugin reads, or a newer one. */
private sealed interface ReportData {
    data class Readable(
        val headSha: String,
        val set: String?,
        val questions: List<QuestionFacts>,
    ) : ReportData

    data object Newer : ReportData
}

/** A whole JSON number, as JavaScript's Number.isInteger allows: `1.0` is one, `"1"` is not. */
internal fun JsonElement?.asWholeNumber(): Double? {
    val primitive = this as? JsonPrimitive ?: return null
    if (primitive.isString) return null
    return primitive.content.toDoubleOrNull()?.takeIf { it.isFinite() && it == Math.floor(it) }
}

/** A whole, non-negative JSON number that fits an Int. */
private fun JsonElement?.asCount(): Int? = asWholeNumber()?.takeIf { it >= 0 && it <= Int.MAX_VALUE }?.toInt()

internal fun JsonElement?.asText(): String? = (this as? JsonPrimitive)?.takeIf { it.isString }?.content

internal fun JsonElement?.asBoolean(): Boolean? = (this as? JsonPrimitive)?.takeIf { !it.isString }?.booleanOrNull

/**
 * Reads the hidden data comment: the first line that is one, wherever it is,
 * since a later layout may move it. Returns [ReportData.Newer] for a version
 * this plugin does not know, whose other fields may mean something else, and
 * null when there is no comment or it is not what the action writes.
 */
private fun readData(lines: List<String>): ReportData? {
    val match = lines.firstNotNullOfOrNull { DATA_COMMENT.find(it) } ?: return null
    val parsed =
        try {
            Json.parseToJsonElement(match.groupValues[1])
        } catch (_: Exception) {
            return null
        }
    val data = parsed as? JsonObject ?: return null

    val version = data["version"].asWholeNumber() ?: return null
    if (version < 1) return null
    if (version > ISSUE_LAYOUT_VERSION) return ReportData.Newer

    val headSha = data["headSha"].asText()?.takeIf { FULL_SHA.matches(it) } ?: return null
    val set =
        data["set"]?.let { element ->
            element.asText()?.takeIf { SET_SLUG.matches(it) } ?: return null
        }
    val questions =
        (data["questions"] as? JsonArray)?.map { element ->
            val q = element as? JsonObject ?: return null
            val snippets =
                (q["snippets"] as? JsonArray)?.map { s ->
                    val snippet = s as? JsonObject ?: return null
                    Triple(
                        snippet["file"].asText() ?: return null,
                        snippet["start_line"].asCount() ?: return null,
                        snippet["end_line"].asCount() ?: return null,
                    )
                } ?: return null
            QuestionFacts(
                number = q["number"].asCount() ?: return null,
                broader = q["broader"].asBoolean() ?: return null,
                snippets = snippets,
            )
        } ?: return null
    return ReportData.Readable(headSha, set, questions)
}

/**
 * Puts the data's facts over what the Markdown gave for the same question:
 * whether it is a broader one, and each snippet's file and lines. A question
 * the data does not list, or lists with another number of snippets, has been
 * edited by hand and is left as the Markdown has it.
 */
private fun withData(
    questions: List<Question>,
    data: ReportData.Readable,
): List<Question> {
    val listed = data.questions.associateBy { it.number }
    return questions.map { question ->
        val facts = listed[question.number]
        if (facts == null || facts.snippets.size != question.snippets.size) return@map question
        question.copy(
            broader = facts.broader,
            snippets =
                question.snippets.zip(facts.snippets) { snippet, (file, start, end) ->
                    snippet.copy(file = file, startLine = start, endLine = end)
                },
        )
    }
}

/**
 * Undoes what the action does to a line of prose on its way into the issue:
 * the bold it wraps around a question's text, and the zero-width space that
 * defuses a mention or an issue reference. Inline code spans are left as they
 * are, as the action leaves them.
 */
private fun plainProse(text: String): String {
    fun prose(part: String) = part.replace("**", "").replace("@$ZWSP", "@").replace("#$ZWSP", "#")

    val out = StringBuilder()
    var at = 0
    for (span in CODE_SPAN.findAll(text)) {
        out.append(prose(text.substring(at, span.range.first))).append(span.value)
        at = span.range.last + 1
    }
    return out.append(prose(text.substring(at))).toString().trim()
}

private data class Header(
    val baseSha: String,
    val headSha: String,
    val branch: String?,
    val tag: String?,
    val files: List<String>,
    val bodyStart: Int,
)

/** Reads the report's header block, or returns null when it is not a report. */
private fun readHeader(lines: List<String>): Header? {
    val first = lines.indexOfFirst { it.isNotBlank() }
    if (first == -1 || !HEADING.containsMatchIn(lines[first])) return null

    val end = (first + 1 until lines.size).firstOrNull { RULE.containsMatchIn(lines[it]) } ?: return null

    var baseSha = ""
    var headSha = ""
    var branch: String? = null
    var tag: String? = null
    var files = emptyList<String>()
    for (line in lines.subList(first + 1, end)) {
        COMMITS.find(line)?.let {
            baseSha = it.groupValues[1]
            headSha = it.groupValues[2]
        }
        BRANCH.find(line)?.let { branch = it.groupValues[1] }
        TAG.find(line)?.let { tag = it.groupValues[1] }
        FILES.find(line)?.let { match ->
            files = CODE_SPAN.findAll(match.groupValues[1]).map { it.value.trim('`') }.toList()
        }
    }
    // Every report names the commits it reviewed. Without them this is some
    // other issue that happens to share the heading.
    return if (headSha.isNotEmpty()) Header(baseSha, headSha, branch, tag, files, end + 1) else null
}

/** A question being read, before it is known to be complete. */
private class Draft(
    val number: Int,
    val broader: Boolean,
) {
    val snippets = mutableListOf<Snippet>()
    var question = ""
    var answer: String? = null

    fun build() = Question(number, broader, snippets.toList(), question, answer)
}

/**
 * Parses a questions issue's body.
 *
 * Returns null when the text is not a GrillMyCode report, [NeedsUpdate] when
 * its layout is newer than this plugin reads (its Markdown may have changed
 * too, so none of it is read), and a [Report] otherwise.
 */
fun parseReport(body: String?): ParsedReport? {
    if (body == null) return null
    val lines = body.split(LINE_BREAK)
    val data = readData(lines)
    if (data == ReportData.Newer) return NeedsUpdate
    val header = readHeader(lines) ?: return null

    val questions = mutableListOf<Question>()
    var current: Draft? = null
    var broader = false
    var caption: Triple<String, Int, Int>? = null
    var awaitingAnswer = false
    var sawFooter = false
    // Whether the rule just passed closed a question, which a cut notice then
    // shows to be the one the cut landed in.
    var ruleClosedQuestion = false

    fun finish(): Boolean {
        val draft = current
        val complete = draft != null && draft.question.isNotEmpty()
        if (complete) questions.add(draft.build())
        current = null
        caption = null
        awaitingAnswer = false
        return complete
    }

    var i = header.bodyStart
    while (i < lines.size) {
        val line = lines[i]
        i++

        if (FOOTER.containsMatchIn(line)) {
            sawFooter = true
            break
        }
        if (RULE.containsMatchIn(line)) {
            ruleClosedQuestion = finish()
            continue
        }
        if (CUT_NOTICE.containsMatchIn(line)) {
            // The action cut the report at a fixed length and closed it with a rule
            // and this notice, so the question before the rule may stop mid-sentence.
            if (ruleClosedQuestion) questions.removeAt(questions.lastIndex)
            break
        }
        if (BROADER_HEADING.containsMatchIn(line)) {
            broader = true
            continue
        }
        val label =
            QUESTION_LABEL
                .find(line)
                ?.groupValues
                ?.get(1)
                ?.toIntOrNull()
        if (label != null) {
            finish()
            ruleClosedQuestion = false
            current = Draft(label, broader)
            continue
        }
        val draft = current ?: continue

        val captioned = CAPTION.find(line)
        if (captioned != null && draft.question.isEmpty()) {
            val start = captioned.groupValues[2].toIntOrNull()
            val end = captioned.groupValues[3].ifEmpty { captioned.groupValues[2] }.toIntOrNull()
            if (start != null && end != null) {
                caption = Triple(captioned.groupValues[1], start, end)
                continue
            }
        }

        val fence = FENCE_OPEN.find(line)
        if (fence != null && draft.question.isEmpty()) {
            // The action picks a fence longer than any run of backticks in the code,
            // so the first line that is exactly the fence closes it.
            val ticks = fence.groupValues[1]
            val close = (i until lines.size).firstOrNull { lines[it].trimEnd() == ticks } ?: break // cut off inside a snippet
            draft.snippets.add(
                Snippet(
                    file = caption?.first ?: "",
                    startLine = caption?.second ?: 0,
                    endLine = caption?.third ?: 0,
                    language = fence.groupValues[2],
                    code = lines.subList(i, close).joinToString("\n"),
                ),
            )
            caption = null
            i = close + 1
            continue
        }

        if (ANSWER_LABEL.containsMatchIn(line)) {
            awaitingAnswer = draft.question.isNotEmpty()
            continue
        }
        if (line.isBlank()) continue

        if (awaitingAnswer) {
            draft.answer = plainProse(line.removePrefix("- "))
            awaitingAnswer = false
        } else if (draft.question.isEmpty()) {
            draft.question = plainProse(line)
        }
    }
    if (sawFooter) finish()

    val readable = data as? ReportData.Readable
    return Report(
        baseSha = header.baseSha,
        headSha = header.headSha,
        headCommit = readable?.headSha,
        branch = header.branch,
        tag = header.tag,
        set = readable?.set,
        files = header.files,
        questions = if (readable != null) withData(questions, readable) else questions,
        truncated = !sawFooter,
    )
}
